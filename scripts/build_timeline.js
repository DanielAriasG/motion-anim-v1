// Lays narration lines on the film timeline: what the picture (motion.js) and the score follow.
//   node build_timeline.js <film dir>
// In:  narration.json ({ lines: [{ id, text, gap, scene }], tail }), vo/<id>.wav + vo/<id>.json (word timings)
// Out: cues.js  CUES = { TOTAL, engine, order, lines: { id: { t0, t1, scene, words: [{ w, s, e }] } } } (absolute s)
//      vo-track.wav  the voice alone, 48 kHz mono, TOTAL long
// `gap` is the silence before a line (leave ~1-1.8 s before a new scene so the picture can change first);
// `tail` is the time after the last line (end card, funding statements: at least 4-6 s).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const dir = path.resolve(process.argv[2] || '.');
const N = JSON.parse(fs.readFileSync(path.join(dir, 'narration.json'), 'utf8'));
const lines = {}, order = [];
let t = 0, engine = null;
for (const L of N.lines) {
  const v = JSON.parse(fs.readFileSync(path.join(dir, 'vo', L.id + '.json'), 'utf8'));
  engine = v.engine;
  t += L.gap ?? .8;
  const t0 = +t.toFixed(3);
  lines[L.id] = {
    t0, t1: +(t0 + v.dur).toFixed(3), scene: L.scene,
    words: v.words.map(w => ({ w: w.w, s: +(t0 + w.s).toFixed(3), e: +(t0 + w.e).toFixed(3) })),
  };
  order.push(L.id);
  t += v.dur;
}
const TOTAL = +(t + (N.tail ?? 5)).toFixed(2);
fs.writeFileSync(path.join(dir, 'cues.js'), '// Generated by build_timeline.js from narration.json and vo/*.json. Do not edit.\n' +
  `const CUES = ${JSON.stringify({ TOTAL, engine, order, lines })};\nif (typeof module !== 'undefined') module.exports = CUES;\n`);

// the voice track: each clip delayed to its start, summed
const ins = [], fl = [];
order.forEach((id, i) => {
  ins.push('-i', path.join(dir, 'vo', id + '.wav'));
  fl.push(`[${i}]adelay=${Math.round(lines[id].t0 * 1000)}:all=1[a${i}]`);
});
fl.push(order.map((_, i) => `[a${i}]`).join('') + `amix=inputs=${order.length}:normalize=0,apad=whole_dur=${TOTAL}[out]`);
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', ...ins, '-filter_complex', fl.join(';'), '-map', '[out]',
  '-t', String(TOTAL), '-ar', '48000', '-ac', '1', '-c:a', 'pcm_s24le', path.join(dir, 'vo-track.wav')]);
console.log(`${engine}: ${order.length} lines, total ${TOTAL} s`);
order.forEach(id => console.log(`  ${id} ${lines[id].t0.toFixed(2)}-${lines[id].t1.toFixed(2)} ${lines[id].scene || ''}`));
